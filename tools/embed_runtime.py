#!/usr/bin/env python3
"""Synchronise readable runtime literals in the one-file configurator.

Edit a canonical runtime file, then run this tool. Python code is
maintained directly in motd.py. No compression, downloading or eval is involved.
--check is a read-only CI gate, not a rebuild.
"""
import argparse
import ast
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
path = root / 'motd.py'
source = path.read_text(encoding='utf-8')
candidate = source
for name, filename in [('DESIGNS', 'designs.sh'), ('BASH', 'motd.bash'), ('SH', 'motd.sh'), ('PS', 'motd.ps1')]:
    runtime = (root / 'runtime' / filename).read_text(encoding='utf-8')
    start = f'# BEGIN EMBEDDED {name} — regenerated by tools/embed_runtime.py\n'
    end = f'# END EMBEDDED {name}\n'
    if candidate.count(start) != 1 or candidate.count(end) != 1:
        raise SystemExit(f'{name} embedding markers are missing or duplicated')
    if "'''" in runtime:
        raise SystemExit(f'{name} contains a triple-single-quote delimiter; choose a safe literal deliberately')
    prefix, rest = candidate.split(start, 1)
    old, suffix = rest.split(end, 1)
    new = name + "_TEMPLATE = r'''" + runtime + "'''\n"
    if args.check and old != new:
        raise SystemExit(f'{name} embedded runtime differs; run python3 tools/embed_runtime.py')
    candidate = prefix + start + new + end + suffix
ast.parse(candidate)
if not args.check and candidate != source:
    path.write_text(candidate, encoding='utf-8')
print('Embedded runtimes match canonical sources' if args.check else 'Embedded runtimes updated')
