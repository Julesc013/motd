#!/usr/bin/env python3
"""Synchronise the readable Bash literal in the one-file configurator.

Edit runtime/motd.bash, then run this tool. The configurator's Python code is
maintained directly in motd.py. No compression, downloading or eval is involved.
--check is a read-only CI gate, not a rebuild.
"""
import argparse
import ast
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
path = root / 'motd.py'
source = path.read_text(encoding='utf-8')
runtime = (root / 'runtime/motd.bash').read_text(encoding='utf-8')
start = '# BEGIN EMBEDDED BASH — regenerated by tools/embed_runtime.py\n'
end = '# END EMBEDDED BASH\n'
if source.count(start) != 1 or source.count(end) != 1:
    raise SystemExit('Embedding markers are missing or duplicated')
if "'''" in runtime:
    raise SystemExit('Runtime contains a triple-single-quote delimiter; choose a safe literal deliberately')
prefix, rest = source.split(start, 1)
old, suffix = rest.split(end, 1)
new = "BASH_TEMPLATE = r'''" + runtime + "'''\n"
if args.check:
    if old != new: raise SystemExit('Embedded runtime differs; run python3 tools/embed_runtime.py')
    print('Embedded runtime matches canonical source')
else:
    candidate = prefix + start + new + end + suffix
    ast.parse(candidate)
    if candidate != source: path.write_text(candidate, encoding='utf-8')
    print('Embedded runtime updated')
