#!/usr/bin/env python3
"""Embed the pinned TOML parser as plain inspectable Python, without exec/eval.

Canonical upstream files and the MIT licence live in vendor/tomli/. The only
transformations are removal of relative/future imports and indentation inside
one factory namespace. Parser algorithms remain upstream source. Python 3.8+.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / 'vendor' / 'tomli'
BEGIN = '# BEGIN EMBEDDED TOMLI\n'
END = '# END EMBEDDED TOMLI\n'
ENTRYPOINT = 'if __name__ == "__main__":\n'


def merged_source(name):
    """Remove imports whose objects are in the shared factory, preserving text."""
    source = (VENDOR / name).read_text(encoding='utf-8')
    tree = ast.parse(source)
    remove = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and (node.level or node.module == '__future__'):
            remove.update(range(node.lineno, node.end_lineno + 1))
    return '\n'.join(line for number, line in enumerate(source.splitlines(), 1)
                     if number not in remove).rstrip() + '\n'


def embedded_source():
    provenance = json.loads((VENDOR / 'provenance.json').read_text(encoding='utf-8'))
    for name, expected in provenance['files_sha256'].items():
        actual = hashlib.sha256((VENDOR / name).read_bytes()).hexdigest()
        if actual != expected:
            raise ValueError('Vendored TOML source differs from its recorded provenance: ' + name)
    licence = (VENDOR / 'LICENSE').read_text(encoding='utf-8')
    lines = [BEGIN.rstrip(), '# Generated by tools/embed_toml.py from pinned Tomli ' + provenance['version'] + '.',
             '# Canonical files: vendor/tomli/. No encoded or dynamically executed Python.',
             *['# ' + line if line else '#' for line in licence.splitlines()], '',
             'def _motd_vendored_tomli():',
             '    """Create the bundled TOML 1.0 parser for Python versions without tomllib."""',
             '    from types import SimpleNamespace', '']
    for name in ('_types.py', '_re.py', '_parser.py'):
        lines.append('    # ----- Canonical upstream source: vendor/tomli/' + name + ' -----')
        lines.extend('    ' + line if line else '' for line in merged_source(name).splitlines())
        lines.append('')
    lines.extend(['    return SimpleNamespace(load=load, loads=loads, TOMLDecodeError=TOMLDecodeError,',
                  '                           __version__=' + repr(provenance['version']) + ')', '',
                  'if tomllib is None:', '    tomllib = _motd_vendored_tomli()', END.rstrip(), ''])
    return '\n'.join(lines)


def updated_source(source):
    block = embedded_source()
    if BEGIN in source or END in source:
        if source.count(BEGIN) != 1 or source.count(END) != 1:
            raise ValueError('Expected exactly one TOML parser marker pair')
        start = source.index(BEGIN); end = source.index(END, start) + len(END)
        return source[:start] + block + source[end:]
    if source.count(ENTRYPOINT) != 1:
        raise ValueError('Expected one final executable entry point')
    position = source.index(ENTRYPOINT)
    return source[:position] + block + '\n' + source[position:]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check embedding without changing the target')
    parser.add_argument('--target', type=Path, default=ROOT / 'motd.py')
    args = parser.parse_args(argv)
    source = args.target.read_text(encoding='utf-8')
    updated = updated_source(source)
    if args.check:
        if source != updated:
            raise SystemExit('Embedded TOML parser is stale; run python3 tools/embed_toml.py')
        print('Embedded TOML parser matches its licensed canonical source')
    else:
        args.target.write_text(updated, encoding='utf-8')
        print('Embedded plain TOML parser in', args.target)


if __name__ == '__main__':
    main()
