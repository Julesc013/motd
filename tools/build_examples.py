SGR = re.compile(r'\x1b\[([0-9;]*)m')


def svg_preview(ansi, caption='Synthetic fixture · generated by the actual Bash renderer'):
    lines = ansi.splitlines(); cell = 8.45; height = 17; pad = 20
    width = max(len(SGR.sub('', line)) for line in lines)
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{int(width*cell+2*pad)}" height="{len(lines)*height+2*pad+27}" role="img" aria-label="Synthetic MOTD preview">',
           '<rect width="100%" height="100%" rx="10" fill="#111827"/>',
           '<g font-family="DejaVu Sans Mono,Consolas,monospace" font-size="14" xml:space="preserve">']
    color = COLORS[7]; weight = 'normal'
    for row, line in enumerate(lines):
        position = 0; previous = 0
        for match in list(SGR.finditer(line)) + [None]:
            end = match.start() if match else len(line)
            text = line[previous:end]
            if text:
                x = pad + position*cell; y = pad + (row+1)*height
                out.append(f'<text x="{x:.2f}" y="{y}" fill="{color}" font-weight="{weight}">{html.escape(text)}</text>')
                position += len(text)
            if not match: break
            for code in [int(v or 0) for v in match[1].split(';')]:
                if code == 0: color=COLORS[7]; weight='normal'
                elif code == 1: weight='bold'
                elif code == 22: weight='normal'
                elif code == 39: color=COLORS[7]
                elif 30 <= code <= 37: color=COLORS[code-30]
                elif 90 <= code <= 97: color=BRIGHT[code-90]
            previous = match.end()
    out += [f'<text x="{pad}" y="{pad+len(lines)*height+25}" fill="#8390a3" font-size="11">{html.escape(caption)}</text>', '</g>', '</svg>']
    return '\n'.join(out)+'\n'


