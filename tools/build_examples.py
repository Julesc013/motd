#!/usr/bin/env python3
"""Regenerate copyable shell examples and previews from the actual renderers.

Run from the repository. The fixture is intentionally synthetic and labelled
DEMO. This build tool never installs hooks or executes configured user calls.
The default text/SVG rebuild needs only Python's standard library and the Bash
runtime's normal tools. Add --png to rasterize the actual wizard frames with the
gallery's Pillow/wcwidth/font dependencies and optional lossless optimizer.
"""
import argparse
import html
import io
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
from unittest.mock import patch
from contextlib import redirect_stdout

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import motd

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--png', action='store_true', help='Also regenerate lossless wizard PNGs at all four terminal sizes')
parser.add_argument('--optimizer', help='Optional oxipng executable for --png')
args = parser.parse_args()

COLORS = ['#171d2b', '#ed6a73', '#74d19b', '#edce77', '#76a9fa', '#c19deb', '#63d1df', '#e4e9f0']
BRIGHT = ['#8390a3', '#ff8590', '#9beaaf', '#ffe599', '#9bc2ff', '#d7b5ff', '#8ae5ef', '#ffffff']
SGR = re.compile(r'\x1b\[([0-9;]*)m')


def svg_preview(ansi, caption='Synthetic fixture · generated by the actual Bash renderer'):
    lines = ansi.splitlines(); cell = 8.45; height = 17; pad = 20
    width = max(len(SGR.sub('', line)) for line in lines)
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{int(width*cell+2*pad)}" height="{len(lines)*height+2*pad+27}" role="img" aria-label="Synthetic MOTD preview">',
           '<rect width="100%" height="100%" rx="10" fill="#111827"/>',
           '<g font-family="DejaVu Sans Mono,Consolas,monospace" font-size="14" xml:space="preserve">']
    color = COLORS[7]; weight = 'normal'
    for row, line in enumerate(lines):
        position = 0; previous = 0
        for match in list(SGR.finditer(line)) + [None]:
            end = match.start() if match else len(line)
            text = line[previous:end]
            if text:
                x = pad + position*cell; y = pad + (row+1)*height
                out.append(f'<text x="{x:.2f}" y="{y}" fill="{color}" font-weight="{weight}">{html.escape(text)}</text>')
                position += len(text)
            if not match: break
            for code in [int(v or 0) for v in match[1].split(';')]:
                if code == 0: color=COLORS[7]; weight='normal'
                elif code == 1: weight='bold'
                elif code == 22: weight='normal'
                elif code == 39: color=COLORS[7]
                elif 30 <= code <= 37: color=COLORS[code-30]
                elif 90 <= code <= 97: color=BRIGHT[code-90]
            previous = match.end()
    out += [f'<text x="{pad}" y="{pad+len(lines)*height+25}" fill="#8390a3" font-size="11">{html.escape(caption)}</text>', '</g>', '</svg>']
    return '\n'.join(out)+'\n'


records=[]
(ROOT/'examples').mkdir(exist_ok=True)
(ROOT/'presets').mkdir(exist_ok=True)
for name in motd.PRESET_NAMES:
    recipe=ROOT/'presets'/f'{name}.toml'
    if not recipe.exists(): recipe.write_text(motd.dump_config(motd.preset_config(name)),encoding='utf-8')
    config=motd.load_config(recipe)
    output=motd.generate_artifact(config)
    extension='.bash' if config['target']=='shell' else '.issue'
    path=ROOT/'examples'/(name+extension)
    path.write_text(output,encoding='utf-8');path.chmod(0o755 if extension=='.bash' else 0o644)
    if config['target']=='shell':
        env=os.environ.copy();env['TERM']='xterm-256color';env.pop('NO_COLOR',None)
        command=['bash',str(path),'--demo','--width','100','--rows','25']
        if any(config['hooks'].values()): command.append('--no-hooks')
        result=subprocess.run(command,env=env,capture_output=True,text=True,check=True,timeout=5)
        (ROOT/'examples'/(name+'.preview.txt')).write_text(SGR.sub('',result.stdout),encoding='utf-8')
        (ROOT/'examples'/(name+'.svg')).write_text(svg_preview(result.stdout),encoding='utf-8')
    records.append({'preset':name,'path':str(path.relative_to(ROOT)),
                    'sha256':motd.hashlib.sha256(output.encode()).hexdigest()})
# SSH pre-authentication text is a distinct serialisation of the public recipe.
public=motd.preset_config('public-console');public['target']='ssh-banner'
for target, filename in [('ssh-banner', 'public-ssh-banner.txt'),
                         ('text', 'public-notice.txt'), ('batch-text', 'public-notice.cmd')]:
    public['target'] = target
    output = motd.generate_artifact(public)
    path = ROOT/'examples'/filename
    path.write_text(output, encoding='utf-8')
    records.append({'preset': 'public-console', 'target': target,
                    'path': str(path.relative_to(ROOT)),
                    'sha256': motd.hashlib.sha256(output.encode()).hexdigest()})

# Every dashboard preset is copyable in every output route. The generated Unix
# files select modern or portable collection at invocation time; native
# PowerShell has the same recoverable recipe format and its own collectors.
for name in ('workshop', 'home-lab'):
    for shell in ('zsh', 'sh', 'powershell', 'fish', 'cmd'):
        config = motd.load_config(ROOT/'presets'/f'{name}.toml')
        motd.select_shell(config, shell)
        output = motd.generate_artifact(config)
        path = ROOT/'examples'/(name + motd.artifact_suffix(config))
        path.write_text(output, encoding='utf-8'); path.chmod(0o755)
        records.append({'preset': name, 'shell': shell, 'path': str(path.relative_to(ROOT)),
                        'sha256': motd.hashlib.sha256(output.encode()).hexdigest()})

# Capture an actual wizard page, with a deterministic terminal and fixture. The
# result is a generated preview of the UI, not a mockup or a live host reading.
class PreviewTerminal(io.StringIO):
    def isatty(self): return True

config = motd.load_config(ROOT/'presets/workshop.toml'); config['display']['theme'] = 'green'


def wizard_frame(columns, rows, *, show_calls=False):
    """Call the same pure frame function used by the interactive terminal UI."""
    sample = motd.validate_config(config)
    if show_calls:
        sample['hooks']['before'] = [
            {'argv': ['fastfetch'], 'timeout_seconds': 2, 'on_failure': 'continue'}]
        sample['hooks']['after'] = [
            {'argv': ['printf', '%s\\n', 'Session ready'],
             'timeout_seconds': 1, 'on_failure': 'continue'}]
    with patch('sys.stdin', PreviewTerminal()), redirect_stdout(PreviewTerminal()), \
         patch('shutil.get_terminal_size', return_value=os.terminal_size((columns, rows))), \
         patch.dict(os.environ, {'TERM': 'xterm-256color'}):
        os.environ.pop('NO_COLOR', None)
        ui = motd.WizardUI('screen'); ui.show_calls = show_calls
        # Build the menu through the live selection method so selection markers,
        # navigation hints and question rows cannot drift from the actual UI.
        def theme_sample(theme):
            selected = motd.copy.deepcopy(sample)
            selected['display']['theme'] = theme
            return selected
        with patch.object(ui, 'read', return_value=''):
            ui.select('Theme', [(value.title(), value) for value in ('cyan', 'green', 'amber', 'mono')],
                      default=1, preview_factory=theme_sample)
        title, lines, selected_config, notice, footer = ui._page
        return ui.frame(title, lines, config=selected_config, notice=notice,
                        footer=footer, prompt='Choice [2]: ')


frame = '\n'.join(wizard_frame(100, 38)) + '\n'
(ROOT/'examples/wizard-theme.preview.txt').write_text('\n'.join(line.rstrip() for line in SGR.sub('', frame).splitlines()).rstrip() + '\n', encoding='utf-8')
(ROOT/'examples/wizard-theme.svg').write_text(svg_preview(frame, 'Actual wizard page · synthetic data · configured calls skipped'), encoding='utf-8')
if args.png:
    # Rasterize terminal cells, retaining each entire grid. No scaling, cropping,
    # editor mockup or execution of user-configured hooks is involved.
    from build_gallery import Renderer, TerminalGrid, SIZES, digest, save_lossless, source_hashes, font_metadata
    renderer = Renderer()
    images = []
    views = [(columns, rows, False) for columns, rows in SIZES] + [(80, 50, True)]
    for columns, rows, show_calls in views:
        lines = wizard_frame(columns, rows, show_calls=show_calls)
        if len(lines) != rows:
            raise RuntimeError(f'Wizard returned {len(lines)} rows for a {rows}-row terminal')
        ansi = '\r\n'.join(lines)
        grid = TerminalGrid(columns, rows, reserve_prompt=False).feed(ansi)
        stem = f'wizard-{"call-samples-" if show_calls else ""}{columns}x{rows}'
        transcript = ROOT/'examples'/(stem + '.ansi')
        transcript.write_bytes(ansi.encode('utf-8'))
        path = ROOT/'examples'/(stem + '.png')
        details = save_lossless(renderer.image(grid, title='MOTD | actual wizard frame'), path,
                                optimizer=args.optimizer)
        images.append({'columns': columns, 'rows': rows, 'control_rows': 10,
                       'preview_rows': rows - 10, 'calls_shown': show_calls,
                       'configured_commands_executed': False, 'png': path.name,
                       'transcript': transcript.name,
                       'transcript_sha256': digest(transcript.read_bytes()),
                       'cell_grid_sha256': grid.fingerprint(), **details})
    shutil.copyfile(ROOT/'examples/wizard-80x25.png', ROOT/'examples/wizard-theme.png')
    wizard_sources = source_hashes()
    wizard_sources['tools/build_examples.py'] = digest(Path(__file__).read_bytes())
    (ROOT/'examples/wizard-manifest.json').write_text(json.dumps({
        'generator': motd.VERSION, 'source_sha256': wizard_sources,
        'raster': {'font_size_px': renderer.font_size,
                   'cell_pixels': [renderer.cell_width, renderer.cell_height],
                   'display_scale': 2, 'font_variants': font_metadata(renderer)},
        'compression': {'pillow_level': 9, 'pillow_optimize': True,
                        'optimizer': subprocess.check_output([args.optimizer, '--version'], text=True).strip() if args.optimizer else None,
                        'decoded_rgba_verified': True},
        'note': 'Same frame function as the live wizard; fixed terminal dimensions; synthetic data; hooks skipped.',
        'images': images}, indent=2) + '\n', encoding='utf-8')
(ROOT/'examples/manifest.json').write_text(json.dumps({'generator':motd.VERSION,'examples':records},indent=2)+'\n')
print('Generated examples from current recipes and embedded runtime')
